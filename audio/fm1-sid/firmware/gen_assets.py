#!/usr/bin/env python3
"""Assets for the SID player firmware, into build/fw/assets.h:
  - an 8x12 bitmap font (DejaVu Sans Mono, ASCII 32..126), one byte per row, MSB left
  - the tunes (PSID files from build/tunes/, see tools/tunes.sh) and the playlist
    firmware/gen_assets.py OUT.h
SPDX-License-Identifier: BSD-2-Clause"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
# (file in build/tunes, song): the playlist, in order
PLAYLIST = [
    ("Rolands_Ratrace.sid", 1), ("Sanxion.sid", 1), ("Sanxion.sid", 2),
    ("Wizball.sid", 7), ("Wizball.sid", 4), ("Wizball.sid", 9), ("Wizball.sid", 2),
    ("Contaxia.sid", 1), ("Thats_the_Way_It_Is_main.sid", 1), ("Pandora.sid", 1),
    ("Killer-Ring.sid", 1), ("Bad_Blood-City.sid", 1), ("Lightforce.sid", 1),
    ("Raw_Recruit.sid", 1), ("Commando.sid", 1), ("Monty_on_the_Run.sid", 1), ("Delta.sid", 1),
    ("Cybernoid_II.sid", 1), ("Last_Ninja.sid", 1), ("Alt_Disco.sid", 1),
]


def font():
    f = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 11)
    rows = []
    for c in range(32, 127):
        im = Image.new("1", (8, 12), 0)
        ImageDraw.Draw(im).text((0, -1), chr(c), font=f, fill=1)
        for y in range(12):
            b = 0
            for x in range(8):
                b |= im.getpixel((x, y)) << (7 - x)
            rows.append(b)
    return rows


def main(out):
    tunes, idx = [], {}
    for name, _ in PLAYLIST:
        if name not in idx:
            p = ROOT / "build" / "tunes" / name
            if not p.exists():
                p = next((ROOT / "build" / "hvsc").rglob(name), None)
            if p is None or p.read_bytes()[:4] != b"PSID":
                continue
            idx[name] = len(tunes)
            tunes.append(p.read_bytes())
    with open(out, "w") as f:
        f.write("/* generated by firmware/gen_assets.py */\n")
        f.write("static const uint8_t FONT[95 * 12] = {")
        f.write(",".join(str(b) for b in font()))
        f.write("};\n")
        for i, t in enumerate(tunes):
            f.write(f"static const uint8_t TUNE{i}[{len(t)}] = {{")
            f.write(",".join(str(b) for b in t))
            f.write("};\n")
        f.write("static const struct { const uint8_t *data; uint32_t len; } TUNES[] = {")
        f.write(",".join(f"{{TUNE{i}, {len(t)}}}" for i, t in enumerate(tunes)))
        f.write("};\n")
        pl = [(idx[n], s) for n, s in PLAYLIST if n in idx]
        f.write("static const struct { uint8_t tune, song; } PLAYLIST[] = {")
        f.write(",".join(f"{{{t}, {s}}}" for t, s in pl))
        f.write("};\n#define NPLAY %d\n" % len(pl))
    print(f"{out}: {len(tunes)} tunes, {len(pl)} playlist entries, {sum(map(len, tunes))} bytes")


if __name__ == "__main__":
    main(sys.argv[1])
