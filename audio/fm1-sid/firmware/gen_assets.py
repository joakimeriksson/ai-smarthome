#!/usr/bin/env python3
"""Assets for the SID player firmware, into build/fw/assets.h:
  - an 8x12 bitmap font (DejaVu Sans Mono, ASCII 32..126), one byte per row, MSB left
  - HOUSE: the firmware's own tune (tools/housetune.py), played when no tune pack is appended
    firmware/gen_assets.py OUT.h
SPDX-License-Identifier: BSD-2-Clause"""
import subprocess
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent


def font():
    f = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 11)
    rows = []
    for c in range(32, 127):
        im = Image.new("1", (8, 12), 0)
        ImageDraw.Draw(im).text((0, -1), chr(c), font=f, fill=1)
        for y in range(12):
            b = 0
            for x in range(8):
                b |= im.getpixel((x, y)) << (7 - x)
            rows.append(b)
    return rows


def main(out):
    house = Path(out).with_name("house.sid")
    subprocess.run([sys.executable, str(ROOT / "tools" / "housetune.py"), str(house)], check=True)
    tune = house.read_bytes()
    with open(out, "w") as f:
        f.write("/* generated by firmware/gen_assets.py */\n")
        f.write("static const uint8_t FONT[95 * 12] = {")
        f.write(",".join(str(b) for b in font()))
        f.write("};\n")
        f.write(f"static const uint8_t HOUSE[{len(tune)}] = {{")
        f.write(",".join(str(b) for b in tune))
        f.write("};\n")
    print(f"{out}: font, house tune {len(tune)} bytes")


if __name__ == "__main__":
    main(sys.argv[1])
