#!/usr/bin/env python3
"""sidlog -> C header for the FM-1 replay bench: fm1/sidlog2h.py IN.sidlog OUT.h (one chip)"""
import struct, sys
b = open(sys.argv[1], 'rb').read()
assert b[:8] == b'SIDLOG1\0'
model, fs, clock, chips, samples, nev, mix = struct.unpack_from('<7I', b, 8)
assert chips == 1
ev = [struct.unpack_from('<IBBBB', b, 36 + 8 * i)[:4] for i in range(nev)]
with open(sys.argv[2], 'w') as f:
    f.write(f'/* generated by fm1/sidlog2h.py from {sys.argv[1]} */\n')
    f.write(f'#define LOG_MODEL {model}\n#define LOG_FS {fs}u\n#define LOG_CLOCK {clock}u\n')
    f.write(f'#define LOG_SAMPLES {samples}u\n#define LOG_NEV {nev}u\n')
    f.write('static const struct { unsigned pos; unsigned char reg, val; } LOG_EV[LOG_NEV] = {\n')
    for pos, chip, reg, val in ev:
        f.write(f'    {{{pos}u, {reg}, {val}}},\n')
    f.write('};\n')
